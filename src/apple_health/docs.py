"""Generate the data dictionary (docs/data_dictionary.md) from the table definitions."""

from __future__ import annotations

from pathlib import Path

import polars as pl

from apple_health.config import Config
from apple_health.schemas import SCHEMA_VERSION, STAGING_TABLES, Table, warehouse_tables


def _dtype(d: object) -> str:
    if isinstance(d, pl.Datetime):
        return "timestamp (UTC)" if d.time_zone == "UTC" else "timestamp (local, naive)"
    if isinstance(d, pl.List):
        return f"list[{_dtype(d.inner)}]"
    names = {
        pl.String: "string",
        pl.Int32: "int32",
        pl.Int64: "int64",
        pl.Float64: "float64",
        pl.Boolean: "bool",
        pl.Date: "date",
    }
    for k, v in names.items():
        if d == k:
            return v
    return str(d)


def _table(t: Table) -> list[str]:
    lines = [f"### `{t.name}`", "", t.doc, ""]
    meta = []
    if t.primary_key:
        meta.append(f"**Primary key:** `{', '.join(t.primary_key)}`")
    if t.partition_by:
        meta.append(
            f"**Partitioned by:** `{t.partition_by}` (hive layout `{t.name}/{t.partition_by}=<value>/`)"
        )
    if t.foreign_keys:
        fks = ", ".join(f"`{c}` → `{p}.{pc}`" for c, p, pc in t.foreign_keys)
        meta.append(f"**References:** {fks}")
    if meta:
        lines += ["  \n".join(meta), ""]
    lines += ["| Column | Type | Description |", "|---|---|---|"]
    for c in t.columns:
        lines.append(f"| `{c.name}` | {_dtype(c.dtype)} | {c.doc.replace('|', '\\|')} |")
    return [*lines, ""]


def data_dictionary(cfg: Config) -> str:
    tables = warehouse_tables(cfg)
    out = [
        "# Data dictionary",
        "",
        "<!-- Generated by `uv run apple-health dictionary` from src/apple_health/schemas.py; "
        "do not edit. -->",
        "",
        f"Schema version {SCHEMA_VERSION}. Files live under the warehouse directory "
        "(`warehouse/` by default): `<layer>/<table>.parquet` for the curated, derived and marts layers, or "
        "a directory of hive partitions for partitioned tables. Mart metrics are defined in "
        "`src/apple_health/marts/metrics.py`.",
        "",
        "Conventions: `*_utc` columns are UTC instants; `*_local` columns are naive wall-clock times "
        "in the row's `tz_name`; `local_date` is the local calendar date. Ids are 16-hex-character "
        "BLAKE2b hashes of the row's natural key, stable across runs and exports. HealthKit `%` "
        "values are fractions (0.97 = 97 %).",
        "",
        "Reading: `pl.scan_parquet('warehouse/curated/fct_quantity_sample', hive_partitioning=True)`.",
        "",
    ]
    layers = (("curated", "Curated layer"), ("derived", "Derived layer"), ("marts", "Marts layer"))
    for layer, title in layers:
        out += [f"## {title}", ""]
        for t in tables.values():
            if t.layer == layer:
                out += _table(t)
    out += [
        "## Staging layer",
        "",
        "Lossless mirrors of the source elements: attribute columns keep the source's camelCase "
        "names and raw string values; `*_nr`/`ordinal` columns are integer lineage keys. Use the "
        "curated layer for analysis.",
        "",
        "| Table | Description |",
        "|---|---|",
    ]
    out += [f"| `{t.name}` | {t.doc} |" for t in STAGING_TABLES.values()]
    return "\n".join(out) + "\n"


def write_data_dictionary(cfg: Config, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(data_dictionary(cfg))
    return path
